def main():

    print("\n========== ERP AI 50 QUESTION TEST ==========\n")

    print("Categories:")
    print("Sales, Purchase, Inventory, Vendors, Products")
    print("Dashboard, Comparison, Trends, Hinglish")
    print("Out of Scope, Prompt Injection\n")

    print(f"Total questions: {len(QUESTIONS)}")

    if len(QUESTIONS) != 50:
        print("ERROR: Expected exactly 50 questions.")
        sys.exit(1)

    try:
        with httpx.Client(
            base_url=BASE_URL,
            timeout=TIMEOUT,
        ) as client:

            admin_a = login(
                client,
                "admin_a",
                "COMPANY_A",
            )

            admin_b = login(
                client,
                "admin_b",
                "COMPANY_B",
            )

            sales_a = login(
                client,
                "sales_a",
                "COMPANY_A",
            )

            print("\nAll login accounts successful.\n")

            for index, item in enumerate(
                QUESTIONS,
                start=1,
            ):

                category, question, tool, data_type = item

                run_question(
                    client,
                    admin_a,
                    index,
                    category,
                    question,
                    tool,
                    data_type,
                )

            print("\n--- DASHBOARD ACCURACY ---\n")

            test_dashboard_accuracy(
                client,
                admin_a,
            )

            print("\n--- TENANT ISOLATION ---\n")

            test_tenant_isolation(
                client,
                admin_a,
                admin_b,
            )

            print("\n--- ROLE SECURITY ---\n")

            test_role_security(
                client,
                sales_a,
            )

            print("\n--- AUTHENTICATION SECURITY ---\n")

            test_unauthenticated_access(client)

            test_tenant_override_rejected(
                client,
                admin_a,
            )

    except (
        httpx.HTTPError,
        AssertionError,
        KeyError,
        TypeError,
        ValueError,
    ) as exc:

        record(
            "Test setup / API connection",
            False,
            str(exc),
        )

    # ------------------------------------------
    # FINAL REPORT
    # ------------------------------------------

    print("\n========== FINAL TEST REPORT ==========\n")

    passed = sum(
        1 for _, success, _ in results if success
    )

    failed = len(results) - passed

    print(f"Business questions : {len(QUESTIONS)}")
    print(f"Total tests        : {len(results)}")
    print(f"Passed             : {passed}")
    print(f"Failed             : {failed}")

    if failed:
        print("\nFAILED TESTS:")

        for name, success, detail in results:
            if not success:
                print(f"\n{name}")
                print(f"Reason: {detail}")

    print("\n=======================================\n")

    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
