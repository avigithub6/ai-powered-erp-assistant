# ==================================================
# DASHBOARD ACCURACY
# ==================================================

def test_dashboard_accuracy(
    client: httpx.Client,
    admin_headers: dict[str, str],
):

    try:
        ai_summary = ask_ai(
            client,
            admin_headers,
            "Give me a complete business dashboard summary.",
        )

        assert ai_summary.get("tool_used") == (
            "dashboard_summary"
        )

        response = client.get(
            "/dashboard/summary",
            headers=admin_headers,
        )

        response.raise_for_status()

        dashboard = response.json()
        ai_data = ai_summary["data"]

        assert number(
            ai_data["total_sales"]
        ) == number(
            dashboard["total_sales"]
        )

        assert number(
            ai_data["total_purchase_value"]
        ) == number(
            dashboard["total_purchase_value"]
        )

        record(
            "AI dashboard matches actual dashboard",
            True,
            "Sales and purchase totals match.",
        )

    except (
        httpx.HTTPError,
        AssertionError,
        KeyError,
        TypeError,
        ValueError,
    ) as exc:

        record(
            "AI dashboard accuracy",
            False,
            str(exc),
        )


# ==================================================
# TENANT ISOLATION
# ==================================================

def test_tenant_isolation(
    client: httpx.Client,
    admin_a: dict[str, str],
    admin_b: dict[str, str],
):

    try:
        response_a = client.get(
            "/dashboard/summary",
            headers=admin_a,
        )

        response_b = client.get(
            "/dashboard/summary",
            headers=admin_b,
        )

        response_a.raise_for_status()
        response_b.raise_for_status()

        sales_a = number(
            response_a.json()["total_sales"]
        )

        sales_b = number(
            response_b.json()["total_sales"]
        )

        assert sales_a != sales_b

        record(
            "Company A and B data separation",
            True,
            f"Company A={sales_a}, Company B={sales_b}",
        )

    except (
        httpx.HTTPError,
        AssertionError,
        KeyError,
        TypeError,
        ValueError,
    ) as exc:

        record(
            "Tenant isolation",
            False,
            str(exc),
        )


