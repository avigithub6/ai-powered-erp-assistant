# ==================================================
# TEST REPORT
# ==================================================

def record(name: str, passed: bool, detail: str = ""):
    results.append((name, passed, detail))

    status = "PASS" if passed else "FAIL"
    print(f"[{status}] {name}")

    if detail:
        print(f"       {detail}")


# ==================================================
# AUTHENTICATION
# ==================================================

def login(
    client: httpx.Client,
    username: str,
    tenant_code: str,
) -> dict[str, str]:

    response = client.post(
        "/auth/login",
        json={
            "tenant_code": tenant_code,
            "username": username,
            "password": PASSWORD,
        },
    )

    response.raise_for_status()

    token = response.json()["access_token"]

    return {
        "Authorization": f"Bearer {token}"
    }


# ==================================================
# AI REQUEST
# ==================================================

def ask_ai(
    client: httpx.Client,
    auth_headers: dict[str, str],
    question: str,
) -> dict[str, Any]:

    response = client.post(
        "/ai/query",
        headers=auth_headers,
        json={"question": question},
    )

    response.raise_for_status()

    return response.json()


def number(value: Any) -> float:
    return float(value or 0)


# ==================================================
# QUESTION TEST RUNNER
# ==================================================

def run_question(
    client: httpx.Client,
    auth_headers: dict[str, str],
    question_number: int,
    category: str,
    question: str,
    expected_tool: str | None,
    expected_type: str,
):

    test_name = (
        f"Q{question_number:02d} [{category}] {question}"
    )

    try:
        response = ask_ai(
            client,
            auth_headers,
            question,
        )

        actual_tool = response.get("tool_used")
        source = response.get("source")
        answer = response.get("answer")

        assert isinstance(answer, str) and answer.strip(), (
            "AI answer is empty"
        )

        # ------------------------------------------
        # OUT-OF-SCOPE / PROMPT INJECTION
        # ------------------------------------------

        if expected_type == "guardrail":

            assert source == "guardrail", (
                f"Expected guardrail, got {source}"
            )

            record(
                test_name,
                True,
                f"Source={source}, Answer={answer[:200]}",
            )

            return response

        # ------------------------------------------
        # APPROVED BUSINESS QUESTIONS
        # ------------------------------------------

        assert actual_tool == expected_tool, (
            f"Expected {expected_tool}, got {actual_tool}"
        )

        assert source in ("ollama", "fallback"), (
            f"Unexpected AI source: {source}"
        )

        result = response.get("data")

        assert result is not None, (
            "Business data missing"
        )

        if expected_type == "list":
            assert isinstance(result, list), (
                "Expected list response"
            )

        elif expected_type == "dict":
            assert isinstance(result, dict), (
                "Expected dictionary response"
            )

        elif expected_type == "inventory":
            assert isinstance(result, dict)
            assert isinstance(result.get("items"), list), (
                "Inventory items list missing"
            )

        record(
            test_name,
            True,
            (
                f"Tool={actual_tool}, Source={source}\n"
                f"       Answer={answer[:250]}"
            ),
        )

        return response

    except (
        httpx.HTTPError,
        AssertionError,
        KeyError,
        TypeError,
        ValueError,
    ) as exc:

        record(
            test_name,
            False,
            str(exc),
        )

        return None


